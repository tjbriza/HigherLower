/**
 * Developer-run YouTube identity catalog generator.
 *
 * Discovery is deliberately bounded: five single-page search.list calls at
 * most (250 results total), plus the existing curated IDs as bootstrap seeds.
 * The committed file stores identities only; live subscriber counts and
 * thumbnails are never snapshotted.
 *
 * Usage:
 *   npm run catalog:youtube-channels
 *   npm run catalog:youtube-channels -- --validate
 */

import {
  readFileSync,
  mkdirSync,
  renameSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = join(SCRIPT_DIR, "..");
const CATALOG_PATH = join(
  PROJECT_ROOT,
  "lib",
  "api",
  "data",
  "youtube-channel-catalog.json",
);
const CURATED_POOLS_PATH = join(PROJECT_ROOT, "lib", "api", "curatedPools.ts");
const API_BASE = "https://www.googleapis.com/youtube/v3";
const CATALOG_VERSION = 1;
const CHANNEL_ID_PATTERN = /^UC[A-Za-z0-9_-]{22}$/;
const SOURCE =
  "YouTube Data API v3 search.list discovery and channels.list identity validation; " +
  "generated by scripts/generate-youtube-channel-catalog.mjs";

// Keep edits to discovery scope explicit and easy to review. The hard limits
// below apply to every run; query/page/candidate budgets are not CLI-overridable.
const DISCOVERY = {
  queries: ["music", "gaming", "news", "sports", "education"],
  maxPagesPerQuery: 1,
  maxSearchCalls: 5,
  resultsPerPage: 50,
  candidateBudget: 500,
};
const MIN_CATALOG_ITEMS = 50;
const CHANNEL_BATCH_SIZE = 50;

function fail(message) {
  console.error(`[youtube-catalog] ERROR: ${message}`);
  process.exit(1);
}

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isValidId(value) {
  return typeof value === "string" && CHANNEL_ID_PATTERN.test(value);
}

function hasOnlyKeys(value, expected) {
  return Object.keys(value).every((key) => expected.includes(key));
}

function validateCatalog(raw) {
  if (
    !isRecord(raw) ||
    !hasOnlyKeys(raw, ["version", "generatedAt", "source", "items"]) ||
    raw.version !== CATALOG_VERSION ||
    typeof raw.generatedAt !== "string" ||
    !Number.isFinite(Date.parse(raw.generatedAt)) ||
    typeof raw.source !== "string" ||
    !raw.source.trim() ||
    !Array.isArray(raw.items)
  ) {
    throw new Error("Catalog metadata or top-level shape is invalid.");
  }

  const ids = new Set();
  let previousId = "";
  for (const item of raw.items) {
    if (
      !isRecord(item) ||
      !hasOnlyKeys(item, ["channelId", "title"]) ||
      !isValidId(item.channelId) ||
      typeof item.title !== "string" ||
      !item.title.trim()
    ) {
      throw new Error("Catalog contains an invalid identity record.");
    }
    if (ids.has(item.channelId)) throw new Error("Catalog contains duplicate IDs.");
    if (previousId && item.channelId < previousId) {
      throw new Error("Catalog is not deterministically sorted by channelId.");
    }
    ids.add(item.channelId);
    previousId = item.channelId;
  }
  if (ids.size < MIN_CATALOG_ITEMS) {
    throw new Error(`Catalog has ${ids.size} records; minimum is ${MIN_CATALOG_ITEMS}.`);
  }
  return raw.items;
}

function getApiKey() {
  const fromProcess = process.env.YOUTUBE_API_KEY?.trim();
  if (fromProcess) return fromProcess;

  // Next loads .env.local for its server process; this standalone Node script
  // reads only the single configured setting and never prints or writes it.
  let envText;
  try {
    envText = readFileSync(join(PROJECT_ROOT, ".env.local"), "utf8");
  } catch {
    return "";
  }
  for (const line of envText.split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?YOUTUBE_API_KEY\s*=\s*(.*?)\s*$/);
    if (!match) continue;
    const value = match[1].replace(/^(['"])(.*)\1$/, "$2").trim();
    if (value) return value;
  }
  return "";
}

async function apiGet(resource, params, apiKey) {
  const url = new URL(`${API_BASE}/${resource}`);
  for (const [key, value] of Object.entries(params)) {
    if (value !== undefined && value !== "") url.searchParams.set(key, String(value));
  }
  url.searchParams.set("key", apiKey);

  let response;
  try {
    response = await fetch(url, { headers: { Accept: "application/json" } });
  } catch {
    throw new Error(`${resource} request failed before receiving a response.`);
  }
  if (!response.ok) {
    // Do not print the request URL or provider response body; either can contain
    // sensitive request context. Status alone is sufficient for diagnosis.
    throw new Error(`${resource} request failed with HTTP ${response.status}.`);
  }
  try {
    return await response.json();
  } catch {
    throw new Error(`${resource} returned invalid JSON.`);
  }
}

function readSeedIds() {
  const source = readFileSync(CURATED_POOLS_PATH, "utf8");
  const ids = [...source.matchAll(/channelId:\s*["']([^"']+)["']/g)].map(
    (match) => match[1],
  );
  if (ids.length === 0 || ids.some((id) => !isValidId(id))) {
    throw new Error("Could not read valid YouTube bootstrap IDs from curatedPools.ts.");
  }
  return ids;
}

function usableThumbnail(snippet) {
  for (const candidate of [
    snippet?.thumbnails?.high?.url,
    snippet?.thumbnails?.medium?.url,
    snippet?.thumbnails?.default?.url,
  ]) {
    if (typeof candidate !== "string" || !candidate.trim()) continue;
    try {
      const parsed = new URL(candidate);
      if (parsed.protocol === "https:") return candidate;
    } catch {
      // Try the next documented thumbnail size.
    }
  }
  return "";
}

function addMetric(map, value) {
  map.set(value, (map.get(value) ?? 0) + 1);
}

async function generate() {
  const apiKey = getApiKey();
  if (!apiKey) throw new Error("YOUTUBE_API_KEY is not configured for this generator.");

  const seedIds = readSeedIds();
  const candidateIds = new Set();
  let rawCandidateCount = 0;
  let duplicateCandidates = 0;
  let invalidSearchIds = 0;
  let rawSearchResults = 0;
  let searchCalls = 0;

  for (const id of seedIds) {
    rawCandidateCount += 1;
    if (candidateIds.has(id)) duplicateCandidates += 1;
    else candidateIds.add(id);
  }

  for (const query of DISCOVERY.queries) {
    if (searchCalls >= DISCOVERY.maxSearchCalls) break;
    let pageToken;
    for (let page = 0; page < DISCOVERY.maxPagesPerQuery; page += 1) {
      if (searchCalls >= DISCOVERY.maxSearchCalls) break;
      if (candidateIds.size >= DISCOVERY.candidateBudget) break;

      const result = await apiGet(
        "search",
        {
          part: "snippet",
          type: "channel",
          order: "videoCount",
          maxResults: DISCOVERY.resultsPerPage,
          q: query,
          pageToken,
        },
        apiKey,
      );
      searchCalls += 1;
      if (!isRecord(result) || !Array.isArray(result.items)) {
        throw new Error("search.list response is missing its items array.");
      }

      rawSearchResults += result.items.length;
      for (const item of result.items) {
        const id = item?.id?.channelId ?? item?.snippet?.channelId;
        if (!isValidId(id)) {
          invalidSearchIds += 1;
          continue;
        }
        rawCandidateCount += 1;
        if (candidateIds.has(id)) {
          duplicateCandidates += 1;
        } else if (candidateIds.size < DISCOVERY.candidateBudget) {
          candidateIds.add(id);
        }
      }
      pageToken = result.nextPageToken;
      if (!pageToken) break;
    }
  }

  const ids = [...candidateIds];
  const resolved = new Map();
  const returnedIds = new Set();
  let hiddenCount = 0;
  let missingSubscriberCounts = 0;
  let nonNumericSubscriberCounts = 0;
  let missingTitles = 0;
  let missingThumbnails = 0;
  let invalidChannelRecords = 0;
  let channelsCalls = 0;
  const seeds = new Set(seedIds);

  for (let offset = 0; offset < ids.length; offset += CHANNEL_BATCH_SIZE) {
    const batch = ids.slice(offset, offset + CHANNEL_BATCH_SIZE);
    const result = await apiGet(
      "channels",
      { part: "snippet,statistics", id: batch.join(",") },
      apiKey,
    );
    channelsCalls += 1;
    if (!isRecord(result) || !Array.isArray(result.items)) {
      throw new Error("channels.list response is missing its items array.");
    }

    for (const channel of result.items) {
      if (!isRecord(channel) || !isValidId(channel.id) || !candidateIds.has(channel.id)) {
        invalidChannelRecords += 1;
        continue;
      }
      if (returnedIds.has(channel.id)) continue;
      returnedIds.add(channel.id);

      const snippet = isRecord(channel.snippet) ? channel.snippet : undefined;
      const stats = isRecord(channel.statistics) ? channel.statistics : undefined;
      const title = typeof snippet?.title === "string" ? snippet.title.trim() : "";
      const imageUrl = usableThumbnail(snippet);
      const rawCount = stats?.subscriberCount;

      let value;
      if (stats?.hiddenSubscriberCount === true) {
        hiddenCount += 1;
      } else if (rawCount === undefined || rawCount === null || rawCount === "") {
        missingSubscriberCounts += 1;
      } else if (
        typeof rawCount !== "string" ||
        !/^\d+$/.test(rawCount) ||
        !Number.isSafeInteger(Number(rawCount))
      ) {
        nonNumericSubscriberCounts += 1;
      } else {
        value = Number(rawCount);
      }

      if (!title) missingTitles += 1;
      if (!imageUrl) missingThumbnails += 1;
      if (
        stats?.hiddenSubscriberCount === true ||
        value === undefined ||
        !title ||
        !imageUrl
      ) {
        continue;
      }

      resolved.set(channel.id, { channelId: channel.id, title, value });
    }
  }

  const missingProviderRecords = ids.length - returnedIds.size;
  const items = [...resolved.values()]
    .map(({ channelId, title }) => ({ channelId, title }))
    .sort((a, b) => (a.channelId < b.channelId ? -1 : a.channelId > b.channelId ? 1 : 0));

  if (items.length < MIN_CATALOG_ITEMS) {
    throw new Error(
      `Only ${items.length} valid identities remain; minimum generation gate is ${MIN_CATALOG_ITEMS}. ` +
        "The existing catalog was not replaced.",
    );
  }

  const values = [...resolved.values()].map((item) => item.value);
  const frequency = new Map();
  for (const value of values) addMetric(frequency, value);
  const tieGroups = [...frequency.values()].filter((count) => count > 1);
  const itemsInTies = tieGroups.reduce((sum, count) => sum + count, 0);
  const sortedValues = [...values].sort((a, b) => a - b);
  const medianValue = sortedValues[Math.floor(sortedValues.length / 2)];
  const duplicateRate = rawCandidateCount
    ? duplicateCandidates / rawCandidateCount
    : 0;
  const catalog = {
    version: CATALOG_VERSION,
    generatedAt: new Date().toISOString(),
    source: SOURCE,
    items,
  };

  validateCatalog(catalog);
  mkdirSync(dirname(CATALOG_PATH), { recursive: true });
  const tempPath = `${CATALOG_PATH}.tmp`;
  writeFileSync(tempPath, `${JSON.stringify(catalog, null, 2)}\n`, "utf8");
  renameSync(tempPath, CATALOG_PATH);

  console.log(`[youtube-catalog] Wrote ${items.length} identity records.`);
  console.log(
    `[youtube-catalog] API calls: search.list=${searchCalls} (max ${DISCOVERY.maxSearchCalls}); ` +
      `channels.list=${channelsCalls} (${CHANNEL_BATCH_SIZE} IDs/request max).`,
  );
  console.log(
    `[youtube-catalog] Candidates: search results=${rawSearchResults}, seeds=${seedIds.length}, ` +
      `raw valid-ID observations=${rawCandidateCount}, unique IDs=${ids.length}, ` +
      `duplicates=${duplicateCandidates} (${(duplicateRate * 100).toFixed(2)}%), ` +
      `invalid search IDs=${invalidSearchIds}.`,
  );
  console.log(
    `[youtube-catalog] Rejected/omitted: hidden subscriber counts=${hiddenCount}, ` +
      `missing subscriber counts=${missingSubscriberCounts}, ` +
      `non-numeric subscriber counts=${nonNumericSubscriberCounts}, ` +
      `missing titles=${missingTitles}, missing thumbnails=${missingThumbnails}, ` +
      `missing provider records=${missingProviderRecords}, ` +
      `invalid channel records=${invalidChannelRecords}.`,
  );
  console.log(
    `[youtube-catalog] Live validation metrics: subscriber range=${sortedValues[0]}–${sortedValues.at(-1)}, ` +
      `distinct values=${frequency.size}/${values.length}, tie groups=${tieGroups.length}, ` +
      `items in ties=${itemsInTies}; seed identities in final catalog=${items.filter((item) => seeds.has(item.channelId)).length}; ` +
      `subscriber median=${medianValue}; popularity cutoff=none (no approved threshold).`,
  );
  console.log(
    "[youtube-catalog] Catalog stores only channelId/title identities; subscriber counts, thumbnails, " +
      "API credentials, and run diagnostics are not written.",
  );
}

async function main() {
  if (process.argv.includes("--validate")) {
    let raw;
    try {
      raw = JSON.parse(readFileSync(CATALOG_PATH, "utf8"));
    } catch {
      throw new Error("Generated catalog is missing or invalid JSON.");
    }
    const items = validateCatalog(raw);
    console.log(
      `[youtube-catalog] Validation passed: ${items.length} unique, sorted identity records; no provider calls made.`,
    );
    return;
  }
  if (process.argv.includes("--probe-invalid-key")) {
    let rejected = false;
    try {
      await apiGet(
        "channels",
        { part: "snippet", id: "UCX6OQ3DkcsbYNE6H8uQQuVA" },
        "invalid-api-key-for-negative-probe",
      );
    } catch {
      rejected = true;
    }
    if (!rejected) throw new Error("Provider did not reject the deliberately invalid credential probe.");
    console.log("[youtube-catalog] Invalid credential probe rejected; credential value and provider body omitted.");
    return;
  }
  await generate();
}

main().catch((error) => fail(error instanceof Error ? error.message : "Unknown generator failure."));
